#!/bin/bash
# Fetch the pinned Haxe toolchain, haxelibs and PocketForge forks named in deps.lock
# into one directory, verifying every download by SHA256 and every clone by commit.
#
# usage: pocketforge/setup-deps.sh [DEPS_DIR]      (default: <repo>/.pf-deps, gitignored)
# then:  . DEPS_DIR/env.sh && haxe compile-linux-gles.hxml
#
# Nothing is written outside DEPS_DIR: HAXELIB_PATH points at DEPS_DIR/haxelib,
# so the user's ~/.haxelib and any global haxelib repository are never used.
set -euo pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
REPO=$(dirname "$HERE")
. "$HERE/deps.lock"
D=${1:-$REPO/.pf-deps}
mkdir -p "$D"
D=$(cd "$D" && pwd -P)
mkdir -p "$D/dl" "$D/toolchain" "$D/src" "$D/haxelib"

fetch() { # url sha256 -> prints local path
	local url=$1 sum=$2 f
	f="$D/dl/$(basename "$url")"
	if ! echo "$sum  $f" | sha256sum -c --status 2>/dev/null; then
		curl -fsSL --retry 3 -o "$f.part" "$url"
		mv "$f.part" "$f"
		echo "$sum  $f" | sha256sum -c --quiet || { echo "SHA256 mismatch: $url" >&2; exit 1; }
	fi
	echo "$f"
}

untar() { # tarball dest
	rm -rf "$2"; mkdir -p "$2"
	tar -xzf "$1" -C "$2" --strip-components=1
}

pin_clone() { # repo sha dest
	local repo=$1 sha=$2 dest=$3
	if [ ! -d "$dest/.git" ]; then
		git init -q "$dest"
		git -C "$dest" remote add origin "$repo"
	fi
	git -C "$dest" fetch -q --depth 1 origin "$sha"
	git -C "$dest" -c advice.detachedHead=false checkout -q --force "$sha"
	[ "$(git -C "$dest" rev-parse HEAD)" = "$sha" ] || { echo "pin mismatch in $dest" >&2; exit 1; }
}

untar "$(fetch "$HAXE_URL" "$HAXE_SHA256")" "$D/toolchain/haxe"
untar "$(fetch "$NEKO_URL" "$NEKO_SHA256")" "$D/toolchain/neko"

cat > "$D/env.sh" <<ENV
# source me: pinned Haxe/Neko and a private haxelib repository (generated by setup-deps.sh)
export PF_DEPS=$D
export PATH=$D/toolchain/haxe:$D/toolchain/neko:\$PATH
export HAXE_STD_PATH=$D/toolchain/haxe/std
export NEKOPATH=$D/toolchain/neko
export LD_LIBRARY_PATH=$D/toolchain/neko\${LD_LIBRARY_PATH:+:\$LD_LIBRARY_PATH}
export HAXELIB_PATH=$D/haxelib
export HASHLINK_SRC=$D/src/hashlink
ENV
. "$D/env.sh"

pin_clone "$HEAPS_REPO" "$HEAPS_SHA" "$D/src/heaps"
pin_clone "$HASHLINK_REPO" "$HASHLINK_SHA" "$D/src/hashlink"

haxelib --never local "$(fetch "$FORMAT_ZIP_URL" "$FORMAT_ZIP_SHA256")" >/dev/null
haxelib --never local "$(fetch "$COLYSEUS_WEBSOCKET_ZIP_URL" "$COLYSEUS_WEBSOCKET_ZIP_SHA256")" >/dev/null
haxelib dev heaps "$D/src/heaps" >/dev/null
haxelib dev hashlink "$D/src/hashlink/other/haxelib" >/dev/null
haxelib dev hlsdl "$D/src/hashlink/libs/sdl" >/dev/null
haxelib dev hlopenal "$D/src/hashlink/libs/openal" >/dev/null

echo "haxe $(haxe --version), haxelib repository $(haxelib config)"
haxelib list
echo "ready: . $D/env.sh"
